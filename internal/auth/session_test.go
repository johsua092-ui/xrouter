func newTestManager(t *testing.T) *Manager {
	t.Helper()
	t.Setenv("JWT_SECRET", "")
	return NewManager(t.TempDir())
}

func TestSignVerifyRoundTrip(t *testing.T) {
	m := newTestManager(t)
	token, err := m.Sign(Claims{"role": "admin"})
	if err != nil {
		t.Fatalf("sign: %v", err)
	}
	if parts := strings.Split(token, "."); len(parts) != 3 {
		t.Fatalf("expected three JWT segments, got %d", len(parts))
	}

	claims, err := m.Verify(token)
	if err != nil {
		t.Fatalf("verify: %v", err)
	}
	if claims["authenticated"] != true {
		t.Fatalf("authenticated claim missing: %#v", claims)
	}
	if claims["role"] != "admin" {
		t.Fatalf("role = %v", claims["role"])
	}
	if _, ok := claims["jti"].(string); !ok {
		t.Fatalf("jti claim missing")
	}
}

func TestVerifyRejectsTamperedToken(t *testing.T) {
	m := newTestManager(t)
	token, err := m.Sign(Claims{"role": "admin"})
	if err != nil {
		t.Fatalf("sign: %v", err)
	}

	parts := strings.Split(token, ".")
	// Flip a character in the payload segment.
	payload := []byte(parts[1])
	if payload[0] == 'e' {
		payload[0] = 'f'
	} else {
		payload[0] = 'e'
	}
	parts[1] = string(payload)

	if _, err := m.Verify(strings.Join(parts, ".")); err == nil {
		t.Fatalf("tampered token verified")
	}
}

func TestVerifyRejectsExpiredToken(t *testing.T) {
	m := newTestManager(t)
	secret, err := m.Secret()
	if err != nil {
		t.Fatalf("secret: %v", err)
	}
	expired := signWithExpiry(t, secret, time.Now().Add(-time.Hour).Unix())
	if _, err := m.Verify(expired); err != ErrExpired {
		t.Fatalf("expected ErrExpired, got %v", err)
	}
}

func TestRevokeKillsTokenAcrossManagers(t *testing.T) {
	dir := t.TempDir()
	t.Setenv("JWT_SECRET", "shared-secret-for-both-runtimes")

	managerA := NewManager(dir)
	token, err := managerA.Sign(Claims{"role": "admin"})
	if err != nil {
		t.Fatalf("sign: %v", err)
	}
	claims, err := managerA.Verify(token)
	if err != nil {
		t.Fatalf("verify: %v", err)
	}
	if err := managerA.Revoke(claims); err != nil {
		t.Fatalf("revoke: %v", err)
	}

	// A second manager (simulating the Node process, or a restart) reads the same
	// revocation file and must reject the token too.
	managerB := NewManager(dir)
	if _, err := managerB.Verify(token); err != ErrRevoked {
		t.Fatalf("expected ErrRevoked, got %v", err)
	}
}

func TestSecretPersistsToDisk(t *testing.T) {
	dir := t.TempDir()
	t.Setenv("JWT_SECRET", "")

	first := NewManager(dir)
	secret, err := first.Secret()
	if err != nil {
		t.Fatalf("secret: %v", err)
	}
	if len(secret) != 64 {
		t.Fatalf("expected 64 hex chars, got %d", len(secret))
	}

	raw, err := os.ReadFile(filepath.Join(dir, "jwt-secret"))
	if err != nil {
		t.Fatalf("read secret file: %v", err)
	}
	if strings.TrimSpace(string(raw)) != string(secret) {
		t.Fatalf("persisted secret differs from in-memory secret")
	}

	second := NewManager(dir)
	again, err := second.Secret()
	if err != nil {
		t.Fatalf("secret: %v", err)
	}
	if string(again) != string(secret) {
		t.Fatalf("secret not reused across managers")
	}
}

// signWithExpiry mints a token with a caller-chosen exp so expiry can be tested
// without sleeping.
func signWithExpiry(t *testing.T, secret []byte, exp int64) string {
	t.Helper()
	header := base64.RawURLEncoding.EncodeToString([]byte(`{"alg":"HS256","typ":"JWT"}`))
	payload := base64.RawURLEncoding.EncodeToString([]byte(
		`{"authenticated":true,"role":"admin","iat":` + strconv.FormatInt(exp-60, 10) +
			`,"exp":` + strconv.FormatInt(exp, 10) + `,"jti":"expired-test"}`))
	mac := hmac.New(sha256.New, secret)
	mac.Write([]byte(header + "." + payload))
	return header + "." + payload + "." + base64.RawURLEncoding.EncodeToString(mac.Sum(nil))
}

func TestCheckPasswordBcryptAndFallback(t *testing.T) {
	m := newTestManager(t)

	// bcrypt hash for "hunter2" generated by the Node dashboard's bcryptjs (cost 10)
	hash, err := HashPassword("hunter2")
	if err != nil {
		t.Fatalf("hash: %v", err)
	}
	if err := m.CheckPassword(hash, "hunter2"); err != nil {
		t.Fatalf("correct password rejected: %v", err)
	}
	if err := m.CheckPassword(hash, "hunter3"); err == nil {
		t.Fatalf("wrong password accepted")
	}

	// Unconfigured install falls back to INITIAL_PASSWORD.
	t.Setenv("INITIAL_PASSWORD", "bootpass")
	if err := m.CheckPassword("", "bootpass"); err != nil {
		t.Fatalf("initial password rejected: %v", err)
	}
	if err := m.CheckPassword("", "nope"); err == nil {
		t.Fatalf("wrong initial password accepted")
	}

	t.Setenv("INITIAL_PASSWORD", "")
	if err := m.CheckPassword("", DefaultPassword); err != nil {
		t.Fatalf("default password rejected: %v", err)
	}
}
